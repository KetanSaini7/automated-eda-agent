import json
import logging
import os
from pathlib import Path

from dotenv import load_dotenv
from google import genai


load_dotenv()

logger = logging.getLogger(__name__)


# ============================================================
# CONFIGURATION
# ============================================================

PROMPT_PATH = (
    Path(__file__).resolve().parent.parent
    / "prompts"
    / "analyst_prompt.txt"
)

# Model confirmed: https://ai.google.dev/gemini-api/docs/models/gemini-3.8-flash
# Thinking levels for gemini-3.8-flash: low, medium, high
# NOTE: "minimal" is NOT supported by gemini-3.8-flash (returns an error).
MODEL_NAME = "gemini-3.8-flash"

# thinking_level="low" is fast and cost-efficient for EDA reports.
# Change to "medium" or "high" for deeper analytical reasoning.
THINKING_LEVEL = "low"

# Maximum attempts (1 original + up to 2 retries = 3 total).
MAX_RETRIES = 3

# Exponential back-off bounds (seconds).
RETRY_WAIT_MIN = 2    # first wait
RETRY_WAIT_MAX = 30   # hard cap

# HTTP status codes that indicate a transient server-side problem worth retrying.
# 400-class codes (bad request, auth failure) are NOT in this set — they are permanent.
_RETRYABLE_CODES = frozenset({429, 500, 503, 504})


# ============================================================
# HELPERS — CLIENT & PROMPT
# ============================================================

def _build_client():
    """
    Create and return a genai.Client authenticated via GOOGLE_API_KEY.
    Raises ValueError if the key is absent; never surfaces the key value.
    """
    api_key = os.environ.get("GOOGLE_API_KEY")

    if not api_key:
        raise ValueError(
            "GOOGLE_API_KEY is not set. "
            "Add it to your .env file or environment variables. "
            "See: https://ai.google.dev/gemini-api/docs/api-key"
        )

    return genai.Client(api_key=api_key)


def load_analyst_prompt():
    """
    Load the analyst instructions from the external prompt file.
    """
    if not PROMPT_PATH.exists():
        raise FileNotFoundError(
            f"Analyst prompt file not found: {PROMPT_PATH}\n"
            "Expected location: prompts/analyst_prompt.txt"
        )

    return PROMPT_PATH.read_text(encoding="utf-8")


# ============================================================
# PROMPT BUILDER  (unchanged interface)
# ============================================================

def build_analysis_prompt(llm_evidence):
    """
    Combine the analyst instructions with compact evidence from
    the Python analysis pipeline.

    The raw dataset is never included — only pre-computed
    statistics and summaries are passed to Gemini.
    """
    analyst_prompt = load_analyst_prompt()

    evidence_json = json.dumps(
        llm_evidence,
        indent=2,
        default=str
    )

    final_prompt = f"""
{analyst_prompt}

--------------------------------------------------
ANALYTICAL EVIDENCE
--------------------------------------------------

The following evidence was generated by the
Python analysis pipeline.

Use this evidence as the source of truth.

{evidence_json}

--------------------------------------------------
END OF ANALYTICAL EVIDENCE
--------------------------------------------------

Now provide the analysis according to the
instructions above.
"""
    return final_prompt


# ============================================================
# RESPONSE EXTRACTION
# ============================================================

def _extract_text_from_interaction(interaction):
    """
    Extract the text content from an interactions.create() response.
    Uses output_text (primary) with a steps-based fallback.
    """
    if interaction is None:
        return None

    # Primary field on the Interactions API response object
    output_text = getattr(interaction, "output_text", None)
    if output_text and output_text.strip():
        return output_text.strip()

    # Fallback: walk interaction steps for model_output content
    steps = getattr(interaction, "steps", None) or []
    for step in steps:
        if getattr(step, "type", None) == "model_output":
            content_blocks = getattr(step, "content", None) or []
            for block in content_blocks:
                text = getattr(block, "text", None)
                if text and text.strip():
                    return text.strip()

    return None


def _extract_text_from_response(response):
    """
    Extract the text content from a models.generate_content() response.
    Handles empty candidates and missing text gracefully.
    """
    if response is None:
        return None

    # Standard .text shortcut
    if hasattr(response, "text"):
        text = response.text
        if text and text.strip():
            return text.strip()

    # Fallback: iterate candidates → content → parts
    for candidate in (getattr(response, "candidates", None) or []):
        content = getattr(candidate, "content", None)
        for part in (getattr(content, "parts", None) or []):
            text = getattr(part, "text", None)
            if text and text.strip():
                return text.strip()

    return None


# ============================================================
# RETRY WRAPPER
# ============================================================

def _call_with_retry(fn, *args, **kwargs):
    """
    Call fn(*args, **kwargs) with exponential back-off + jitter for transient
    Gemini server errors.

    Retriable HTTP codes  : 429 RESOURCE_EXHAUSTED, 500 INTERNAL,
                            503 UNAVAILABLE, 504 DEADLINE_EXCEEDED
    Non-retriable codes   : 400 BAD_REQUEST, 401/403 auth failures, etc.
                            (google.genai raises these as ClientError, which is
                            NOT a subclass of ServerError, so they propagate
                            immediately without any retry.)

    Retry-After header    : If the server supplies a ``Retry-After`` value it is
                            respected (capped at RETRY_WAIT_MAX).

    After all retries are exhausted the function raises a RuntimeError with a
    user-friendly message so callers can surface it cleanly to the UI.
    """
    import random
    import time
    from google.genai import errors as genai_errors

    last_error = None
    wait = RETRY_WAIT_MIN

    for attempt in range(1, MAX_RETRIES + 1):
        try:
            return fn(*args, **kwargs)

        except genai_errors.ClientError:
            # 4xx errors (bad API key, auth failure, malformed request) are
            # permanent — do NOT retry, re-raise immediately.
            raise

        except genai_errors.ServerError as exc:
            # Read the numeric HTTP status code from the .code attribute.
            # (The old code used getattr(exc, "status_code", None) which always
            # returned None because the real attribute is .code.)
            http_code = getattr(exc, "code", None)

            if http_code not in _RETRYABLE_CODES:
                # Non-retriable server error (e.g. unexpected 501) — re-raise.
                raise

            last_error = exc

            if attempt >= MAX_RETRIES:
                # Retries exhausted — convert to a friendly RuntimeError.
                break

            # --- Respect server-provided Retry-After when present ---
            server_wait = None
            try:
                response = getattr(exc, "response", None)
                if response is not None:
                    headers = getattr(response, "headers", {}) or {}
                    ra = headers.get("Retry-After") or headers.get("retry-after")
                    if ra is not None:
                        server_wait = min(float(ra), RETRY_WAIT_MAX)
            except Exception:
                pass  # If header parsing fails, fall back to computed wait

            # --- Exponential back-off with ±25 % jitter ---
            jitter = random.uniform(0.75, 1.25)
            sleep_secs = server_wait if server_wait is not None else min(wait * jitter, RETRY_WAIT_MAX)

            logger.warning(
                "Gemini API transient error (HTTP %s) on attempt %d/%d — "
                "retrying in %.1fs. Error: %s",
                http_code, attempt, MAX_RETRIES, sleep_secs, exc,
            )

            time.sleep(sleep_secs)
            wait = min(wait * 2, RETRY_WAIT_MAX)   # advance back-off for next loop

        except Exception:
            # Any other unexpected exception propagates immediately.
            raise

    # All retries exhausted — raise a friendly RuntimeError.
    raise RuntimeError(
        "Gemini is temporarily unavailable (the service returned a transient "
        f"error after {MAX_RETRIES} attempts). Please try again in a few seconds. "
        f"Technical detail: {last_error}"
    ) from last_error


# ============================================================
# PRIMARY PATH — Interactions API (gemini-3.8-flash native)
# ============================================================

def _generate_via_interactions(client, analysis_prompt):
    """
    Use client.interactions.create() with thinking_level for
    native gemini-3.8-flash generation.

    Supported thinking_levels for this model: low, medium, high
    (Note: 'minimal' is NOT supported and causes an API error.)
    """
    interaction = _call_with_retry(
        client.interactions.create,
        model=MODEL_NAME,
        input=analysis_prompt,
        generation_config={
            "thinking_level": THINKING_LEVEL
        }
    )

    return _extract_text_from_interaction(interaction)


# ============================================================
# FALLBACK PATH — generateContent API
# ============================================================

def _generate_via_generate_content(client, analysis_prompt):
    """
    Fallback: classic models.generate_content API.
    Used when the Interactions API returns nothing or errors out.
    """
    response = _call_with_retry(
        client.models.generate_content,
        model=MODEL_NAME,
        contents=analysis_prompt
    )

    return _extract_text_from_response(response)


# ============================================================
# PUBLIC API  (unchanged interface: generate_analysis)
# ============================================================

def generate_analysis(analysis_prompt):
    """
    Send the analysis prompt to Gemini (gemini-3.8-flash) and
    return the generated natural-language report as a string.

    Strategy:
    1. Try the Interactions API with thinking_level (primary).
    2. Fall back to models.generate_content if interactions fails.

    Error handling:
    - Missing API key → clear message, key never exposed
    - 503 / 429 transient errors → up to MAX_RETRIES retries
    - 401 / 403 → clear auth/permission message
    - Network error → user-friendly message
    - Empty response → user-friendly message
    - Unexpected error → safe fallback message, no raw traceback
    """
    from google.genai import errors as genai_errors

    # ---- Build client -------------------------------------------
    try:
        client = _build_client()
    except ValueError as exc:
        return f"⚠️ Configuration error: {exc}"

    # ---- Try Interactions API first (native 3.8-flash path) -----
    text = None

    try:
        text = _generate_via_interactions(client, analysis_prompt)

    except genai_errors.ClientError as exc:
        status_code = getattr(exc, "status_code", None)
        if status_code == 401:
            return (
                "⚠️ Authentication failed: the GOOGLE_API_KEY is invalid "
                "or has expired. Check your .env file."
            )
        if status_code == 403:
            return (
                f"⚠️ Access denied: your API key does not have permission "
                f"to use {MODEL_NAME}. Check your API quota and project settings."
            )
        # Other client error → fall through to fallback
        text = None

    except genai_errors.ServerError as exc:
        status_code = getattr(exc, "status_code", None)
        if status_code == 503:
            # Already retried MAX_RETRIES times — report clearly
            return (
                f"⚠️ {MODEL_NAME} is currently experiencing high demand. "
                "Please try again in a few moments."
            )
        # Other server error → fall through to fallback
        text = None

    except Exception:
        # Interactions API unavailable or unexpected SDK change → fallback
        text = None

    # ---- Fallback to generate_content if needed -----------------
    if not text:
        try:
            text = _generate_via_generate_content(
                client, analysis_prompt
            )

        except genai_errors.ClientError as exc:
            status_code = getattr(exc, "status_code", None)
            if status_code == 401:
                return (
                    "⚠️ Authentication failed: the GOOGLE_API_KEY is "
                    "invalid or has expired."
                )
            if status_code == 403:
                return (
                    f"⚠️ Access denied: your API key does not have "
                    f"permission to use {MODEL_NAME}."
                )
            return (
                "⚠️ The Gemini API returned an error. "
                f"Please try again. (HTTP {status_code})"
            )

        except genai_errors.ServerError as exc:
            status_code = getattr(exc, "status_code", None)
            if status_code == 503:
                return (
                    f"⚠️ {MODEL_NAME} is currently experiencing high "
                    "demand. Please try again in a few moments."
                )
            return (
                "⚠️ A server error occurred while generating the "
                "analysis. Please try again."
            )

        except OSError:
            return (
                "⚠️ Network error: unable to reach the Gemini API. "
                "Check your internet connection and try again."
            )

        except Exception:
            return (
                "⚠️ An unexpected error occurred while generating the "
                "analysis. Please try again."
            )

    # ---- Empty-response guard -----------------------------------
    if not text:
        return (
            "⚠️ The model returned an empty response. "
            "This can happen with very large prompts or during "
            "high-demand periods. Please try again."
        )

    return text